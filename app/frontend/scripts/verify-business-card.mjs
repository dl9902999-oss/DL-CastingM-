import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const exports = {};
new Function('exports', ts.transpileModule(readFileSync('src/lib/businessCard.ts','utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(exports);
const parse = exports.parseBusinessCard;
const r = parse('測 試 精 密 股 份 有 限 公 司\n王 小 明 經 理\nTEL: (04) 2345-6789 #123  FAX: 04-2345-6790  Mobile: 0912-345-678\nEmail: test@example.com.tw  www.example.com.tw\n地址: 台中市大里區工業路\n12號3樓');
assert.equal(r.company_name,'測試精密股份有限公司');
assert.equal(r.contact_name,'王小明');
assert.equal(r.contact_title,'經理');
assert.equal(r.phone,'(04) 2345-6789 #123');
assert.equal(r.fax,'04-2345-6790');
assert.equal(r.mobile,'0912-345-678');
assert.equal(r.email,'test@example.com.tw');
assert.equal(r.website,'www.example.com.tw');
assert.equal(r.address,'台中市大里區工業路12號3樓');
assert.equal(parse('電話：＋８８６－９１２－３４５－６７８').mobile,'+886-912-345-678');
assert.equal(parse('FAX: 02-23456789').phone,'');
assert.equal(parse('info@example.com').website,'');
assert.equal(parse('Example Co., Ltd.').company_name,'Example Co., Ltd.');
assert.equal(parse('').company_name,'');
console.log('PASS: mixed contact fields, Chinese spacing, name/title separation, international mobile, email/domain, multiline address, fax isolation.');
